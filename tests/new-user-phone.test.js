"use strict";
const {test}=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const source=fs.readFileSync(path.join(__dirname,"..","server","app.js"),"utf8");
test("SMS-auth account creation enrolls phone once in insertUser transaction",()=>{
 const fnStart=source.indexOf("function insertUser(");
 const fnEnd=source.indexOf("function audit(",fnStart);
 const createStart=source.indexOf('if (method === "POST" && route === "/api/users")');
 const createEnd=source.indexOf("const phoneUpdate=",createStart);
 assert.ok(fnStart>=0&&fnEnd>fnStart&&createStart>=0&&createEnd>createStart);
 const insert=source.slice(fnStart,fnEnd),route=source.slice(createStart,createEnd);
 assert.match(insert,/INSERT INTO phone_accounts\(user_id,phone\) VALUES\(\?,\?\)/);
 assert.match(route,/if \(authMode === "sms"\) requireCondition\(normalizePhone\(body\.phone\)/);
 assert.match(route,/return atomic\(db, \(\) => \{/);
 assert.match(route,/const id = insertUser\(db, body\)/);
 assert.doesNotMatch(route,/INSERT INTO phone_accounts/);
 assert.equal((insert.match(/INSERT INTO phone_accounts/g)||[]).length,1);
});
